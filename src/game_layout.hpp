// Select a complete profile by exact executable hash. Never mix addresses across builds.
struct BuildLayout {
    std::string_view hash;
    std::uintptr_t camera_update_rva, mode_rva, mirror_rva, projection_builder_rva;
    std::uintptr_t fov_setter_rva, render_camera_rva, render_vtable_rva, override_flag_rva;
    std::uintptr_t mode_setter_rva, lens_constructor_rva, projection_caller_rva;
};
