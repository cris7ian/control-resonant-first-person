constexpr BuildLayout current_build = {
    supported_hash,
    0x207BFA0, 0x5C24088, 0x17D8E10, 0x1BD5660,
    0x32285C0, 0x5C23AC0, 0x478B4B0, 0x5C237E8,
    0x1BCEC30, 0x32282D0, 0x1BD5240};
constexpr std::array supported_builds = {legacy_build, current_build};
constexpr const BuildLayout* select_build(std::string_view hash) {
    for (const auto& build : supported_builds) if (build.hash == hash) return &build;
    return nullptr;
}

